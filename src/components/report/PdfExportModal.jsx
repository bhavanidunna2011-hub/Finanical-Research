import React, { useState } from "react";
import {
  X,
  Printer,
  Download,
  AlertTriangle,
  CheckCircle2,
  FileCheck2,
  RefreshCw,
  ArrowLeft,
  Info,
  ShieldCheck,
  Sparkles
} from "lucide-react";

export default function PdfExportModal({
  open,
  onClose,
  report,
  onPrint,
  onReturnToLibrary
}) {
  if (!open || !report) return null;

  const [exportState, setExportState] = useState("idle"); // "idle" | "generating" | "success" | "error"
  const [progress, setProgress] = useState(0);
  const [stageText, setStageText] = useState("");
  const [errorMessage, setErrorMessage] = useState("");

  function handleStartSimulation(forceError = false) {
    setExportState("generating");
    setProgress(15);
    setStageText("Initializing headless PDF compilation engine...");

    setTimeout(() => {
      setProgress(40);
      setStageText("Rendering high-resolution vector financial charts & ratio tables...");

      setTimeout(() => {
        if (forceError) {
          setExportState("error");
          setErrorMessage("Simulated timeout: Backend rendering cluster did not respond within the allocated 15s window.");
          return;
        }

        setProgress(75);
        setStageText("Injecting audited page citation anchors and digital watermark...");

        setTimeout(() => {
          setProgress(100);
          setStageText("Packaging printable PDF dossier bundle...");

          setTimeout(() => {
            setExportState("success");
          }, 400);
        }, 600);
      }, 700);
    }, 600);
  }

  function handleSimulatedDownload() {
    // Create a mock blob download to simulate client-side file save
    const element = document.createElement("a");
    const file = new Blob([
      `%PDF-1.4\n% Mock Research Dossier: ${report.title}\n% Generated by FinResearch AI Financial System\n`
    ], { type: "application/pdf" });
    element.href = URL.createObjectURL(file);
    element.download = `${report.title.replace(/[^a-zA-Z0-9]/g, "_")}.pdf`;
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  }

  return (
    <div className="fin-modal-overlay" onClick={onClose} role="dialog" aria-modal="true">
      <div className="fin-export-modal-card" onClick={(e) => e.stopPropagation()}>
        {/* Header */}
        <div className="modal-header-row">
          <div className="flex-row items-center gap-2">
            <div className="modal-icon-badge">
              <Download size={20} className="text-teal" />
            </div>
            <div>
              <h3 className="text-base font-bold text-main">Export Research Report</h3>
              <span className="text-xs text-muted block truncate max-w-sm">
                {report.title}
              </span>
            </div>
          </div>

          <button
            type="button"
            className="modal-close-btn"
            onClick={onClose}
            aria-label="Close export modal"
          >
            <X size={18} />
          </button>
        </div>

        {/* Body */}
        <div className="modal-body-scroll export-modal-body">
          {/* Institutional Note on Backend Services */}
          <div className="export-policy-notice mb-4">
            <Info size={16} className="text-teal flex-shrink-0 mt-0.5" />
            <p className="text-xs text-muted leading-relaxed">
              <strong>PDF Export Notice:</strong> An external server-side PDF generation service is not connected in this frontend environment. You can use <strong>Browser Print / Save as PDF</strong> (which formats the dossier for A4/Letter print) or run the <strong>simulated compilation pipeline</strong> to preview progress and feedback states.
            </p>
          </div>

          {/* Idle State Options */}
          {exportState === "idle" && (
            <div className="export-options-grid">
              {/* Option 1: Native Print to PDF */}
              <div className="export-option-card">
                <div className="flex-row items-center gap-2 mb-1">
                  <Printer size={18} className="text-teal" />
                  <strong className="text-sm text-main">Native Print / Save to PDF</strong>
                  <span className="fin-badge fin-badge-teal fin-badge-xs ml-auto">Recommended</span>
                </div>
                <p className="text-xs text-muted leading-relaxed">
                  Triggers the native browser print dialog with institutional print styling. Formats margins, hides interface controls, and enables saving directly as a clean PDF file.
                </p>
                <button
                  type="button"
                  className="fin-btn fin-btn-primary fin-btn-sm w-full mt-3"
                  onClick={() => {
                    onClose();
                    if (onPrint) onPrint();
                  }}
                >
                  <Printer size={14} className="mr-1.5" />
                  <span>Launch Print / Save PDF</span>
                </button>
              </div>

              {/* Option 2: Simulated Server-Side PDF Service */}
              <div className="export-option-card">
                <div className="flex-row items-center gap-2 mb-1">
                  <Sparkles size={18} className="text-purple-400" />
                  <strong className="text-sm text-main">Simulate PDF Service Pipeline</strong>
                  <span className="fin-badge fin-badge-purple fin-badge-xs ml-auto">Demo State</span>
                </div>
                <p className="text-xs text-muted leading-relaxed">
                  Demonstrates the asynchronous report compilation workflow, progress bar telemetry, and success/failure handling for future Report Agent backend integration.
                </p>
                <div className="flex-row gap-2 mt-3">
                  <button
                    type="button"
                    className="fin-btn fin-btn-secondary fin-btn-sm flex-1"
                    onClick={() => handleStartSimulation(false)}
                  >
                    <span>Simulate Success</span>
                  </button>
                  <button
                    type="button"
                    className="fin-btn fin-btn-secondary fin-btn-sm"
                    onClick={() => handleStartSimulation(true)}
                    title="Test error feedback state"
                  >
                    <span>Simulate Error</span>
                  </button>
                </div>
              </div>
            </div>
          )}

          {/* Generating Progress State */}
          {exportState === "generating" && (
            <div className="export-progress-container text-center py-6 animate-fadeIn">
              <div className="export-progress-spinner mb-3">
                <RefreshCw size={28} className="text-teal spin-slow" />
              </div>
              <h4 className="text-sm font-bold text-main">Compiling Research Dossier</h4>
              <p className="text-xs text-muted mt-1 max-w-sm mx-auto">
                {stageText}
              </p>

              <div className="export-progress-bar-wrap mt-4">
                <div className="fin-progress-track">
                  <div
                    className="fin-progress-bar-teal transition-all duration-300"
                    style={{ width: `${progress}%` }}
                  />
                </div>
                <div className="flex-row justify-between text-[11px] text-muted mt-1 font-mono">
                  <span>Progress</span>
                  <span>{progress}%</span>
                </div>
              </div>
            </div>
          )}

          {/* Success State */}
          {exportState === "success" && (
            <div className="export-success-container text-center py-5 animate-fadeIn">
              <div className="success-icon-wrap mb-2">
                <CheckCircle2 size={36} className="text-success mx-auto" />
              </div>
              <h4 className="text-base font-bold text-main">PDF Dossier Successfully Compiled</h4>
              <p className="text-xs text-muted mt-1 max-w-md mx-auto leading-relaxed">
                The research report bundle has been assembled with 100% verified citations, audited balance sheet ratios, and executive highlights.
              </p>

              <div className="mt-4 flex-row justify-center gap-2">
                <button
                  type="button"
                  className="fin-btn fin-btn-primary fin-btn-sm"
                  onClick={handleSimulatedDownload}
                >
                  <Download size={14} className="mr-1.5" />
                  <span>Download Generated File</span>
                </button>
                <button
                  type="button"
                  className="fin-btn fin-btn-secondary fin-btn-sm"
                  onClick={() => setExportState("idle")}
                >
                  Reset Options
                </button>
              </div>
            </div>
          )}

          {/* Error State */}
          {exportState === "error" && (
            <div className="export-error-container text-center py-5 animate-fadeIn">
              <div className="error-icon-wrap mb-2">
                <AlertTriangle size={36} className="text-danger mx-auto" />
              </div>
              <h4 className="text-base font-bold text-danger">Report Generation Failed</h4>
              <p className="text-xs text-muted mt-1 max-w-md mx-auto leading-relaxed">
                {errorMessage}
              </p>

              <div className="mt-4 flex-row justify-center gap-2">
                <button
                  type="button"
                  className="fin-btn fin-btn-primary fin-btn-sm"
                  onClick={() => handleStartSimulation(false)}
                >
                  <RefreshCw size={13} className="mr-1" />
                  <span>Retry Export</span>
                </button>
                <button
                  type="button"
                  className="fin-btn fin-btn-secondary fin-btn-sm"
                  onClick={() => setExportState("idle")}
                >
                  Back to Options
                </button>
              </div>
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="modal-footer-row">
          <button
            type="button"
            className="fin-btn fin-btn-secondary fin-btn-sm"
            onClick={onReturnToLibrary}
          >
            <ArrowLeft size={13} className="mr-1" />
            <span>Return to Report Library</span>
          </button>
          <button
            type="button"
            className="fin-btn fin-btn-secondary fin-btn-sm"
            onClick={onClose}
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
}
